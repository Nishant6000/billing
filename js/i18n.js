export const getLanguage = () => localStorage.getItem('pos-language') || 'en';

export const setLanguage = (language) => {
  const code = dictionaries[language] ? language : 'en';
  localStorage.setItem('pos-language', code);
  document.documentElement.lang = code;
};

export const t = (key) => dictionaries[getLanguage()]?.[key] || dictionaries.en[key] || key;

export const routeTitle = (route) => t(`route.${route.id}`);

export const displayTableName = (name = '') => {
  const value = String(name || '');
  const match = value.match(/^Table\s+(\d+)$/i);
  return match ? `${t('table')} ${match[1]}` : value;
};

export const displayTableArea = (area = '') => {
  const value = String(area || '');
  const normalized = value.toLowerCase();
  if (normalized === 'ground floor') return t('groundFloor');
  if (normalized === 'family') return t('family');
  if (normalized === 'dining') return t('dining');
  if (normalized === 'outdoor') return t('outdoor');
  return value;
};

export const displayStatus = (status = '') => {
  const normalized = String(status || 'available').toLowerCase();
  return t(normalized) || status;
};

export const localizedProductName = (product = {}) => {
  const language = getLanguage();
  if (language === 'en') return product.product_name || '';
  return product[`product_name_${language}`] || product.product_name || '';
};
